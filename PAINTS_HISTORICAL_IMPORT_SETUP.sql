-- Run ONCE in Supabase SQL Editor before importing the Paints workbook.
-- This is a dedicated historical ledger. It does not overwrite existing paint tables.
CREATE TABLE IF NOT EXISTS public.paint_historical_financials (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vessel text NOT NULL,
  year integer NOT NULL CHECK (year BETWEEN 2000 AND 2100),
  kind text NOT NULL CHECK (kind IN ('actual','budget')),
  amount numeric(16,2) NOT NULL CHECK (amount >= 0),
  created_by uuid NOT NULL REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(vessel,year,kind)
);
ALTER TABLE public.paint_historical_financials ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS paint_historical_read ON public.paint_historical_financials;
CREATE POLICY paint_historical_read ON public.paint_historical_financials FOR SELECT TO authenticated USING (
 EXISTS(SELECT 1 FROM public.fleet_members f WHERE f.user_id=auth.uid())
 OR EXISTS(SELECT 1 FROM public.marine_manager_members m WHERE m.user_id=auth.uid())
);
DROP POLICY IF EXISTS paint_historical_owner_import ON public.paint_historical_financials;
CREATE POLICY paint_historical_owner_import ON public.paint_historical_financials FOR INSERT TO authenticated WITH CHECK (
 created_by=auth.uid() AND lower(auth.jwt()->>'email')='dkarakasilis@marantankers.gr'
 AND EXISTS(SELECT 1 FROM public.fleet_members f WHERE f.user_id=auth.uid())
);
GRANT SELECT, INSERT ON public.paint_historical_financials TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.paint_historical_financials_id_seq TO authenticated;
